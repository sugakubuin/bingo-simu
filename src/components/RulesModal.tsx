import { useEffect, useRef } from "react";

type Props = {
  open: boolean;
  onClose: () => void;
};

export function RulesModal({ open, onClose }: Props) {
  const ref = useRef<HTMLDialogElement>(null);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (open && !el.open) el.showModal();
    if (!open && el.open) el.close();
  }, [open]);

  return (
    <dialog
      ref={ref}
      className="rules-dialog"
      aria-labelledby="rules-title"
      onClose={onClose}
      onClick={onClose}
    >
      <div
        className="rules-dialog-panel"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="rules-dialog-head">
          <h2 id="rules-title">確変チューリップのルール</h2>
          <button
            type="button"
            className="help-q"
            aria-label="閉じる"
            onClick={onClose}
          >
            ×
          </button>
        </div>
        <div className="rules-dialog-body">
          <section>
            <h3>チューリップとは</h3>
            <p>
              祝儀麻雀の一種です。和了したとき、ツモ山の上段をドラ表示牌の側から順に1トンずつめくります。めくった牌と、その前後の牌が手牌（および抜き牌）に含まれていれば、その枚数だけ祝儀がのります。1枚ものらなかった時点で終了しますが、のる限りは山の端までめくり続けます。
            </p>
          </section>

          <section>
            <h3>基本ルール</h3>
            <ul>
              <li>
                ・リーチ、あるいは本役満で和了したときのみ、チューリップをめくれます。役満はリーチしていなくてもよく、副露役満も対象です。
              </li>
              <li>
                ・一発・白ポッチ・三倍満以上の和了には転落保証が付きます。0枚のトンで終了するはずのところを1回スキップできます。複数あれば連続して使えます。
              </li>
              <li>
                ・白ポッチ、およびウルトラビンゴでの7mツモは、チューリップをめくる前にどの牌とするかを決めます。白ポッチは7と見れば確変にもなり得ます。本シミュレーターの手牌入力は、読み替え済みのものにしてください。
              </li>
            </ul>
          </section>

          <section>
            <h3>チューリップののり判定</h3>
            <p>
              牌は循環しています。めくり牌Xに対し、手前・自身・次の3種が手牌にあれば、その合計枚数がのります。手牌の牌は毎回再利用されます。槓子は4枚として数えます。
            </p>
            <ul>
              <li>筒子・索子: 1→2→…→9→1</li>
              <li>風牌: 東→南→西→北→東</li>
              <li>三元牌: 白→發→中→白（3枚循環のため、白がめくれると白發中のすべて）</li>
            </ul>
            <p>
              花牌がめくれたときは、抜いている花牌の枚数×3枚のります。
            </p>
          </section>

          <section>
            <h3>確変</h3>
            <p>
              手牌に同色の7が3枚以上あるとき、チューリップは確変になります。暗刻として使っている必要はありません。確変では上段に加えて下段もめくれ、上下どちらものらなかった時点で終了します。
            </p>
          </section>

          <section>
            <h3>突確</h3>
            <p>
              1回のめくりで6枚以上のると突確に入ります。上下の合計が6枚でも、1枚あたりが6枚未満なら入りません。入ると次のトンから確変になり、下段もめくれるようになります。
            </p>
          </section>

          <section>
            <h3>16R</h3>
            <p>次のいずれかのとき、確変の上位である16Rに入ります。</p>
            <ul>
              <li>・手牌が「777の777」（7pが3枚以上、かつ7sが3枚以上）</li>
              <li>・リーチ役満・天地人和で、同色の7が3枚以上あるとき</li>
              <li>・確変中に突確へ入ったとき</li>
            </ul>
            <p>
              16Rでは、終了時の合計枚数が2倍になります。条件が重なっても2倍のままです。
            </p>
          </section>

          <section>
            <h3>スーパービンゴ（112枚）</h3>
            <p>
              萬子は入りません。7pと7sのみ8枚ずつ、その他の筒索は各4枚、字牌各4枚、花牌4枚です。
            </p>
            <ul>
              <li>
                ・花牌では突確しません。6枚や9枚のっても、状態は変わりません。
              </li>
              <li>
                ・手牌の中で7p、7sを5枚以上使って和了ることはできません（麻雀の常識）。
              </li>
            </ul>
          </section>

          <section>
            <h3>ウルトラビンゴ（108枚）</h3>
            <p>
              1m・9mの代わりに7mを4枚入れた確変チューリップです。筒索字は各4枚、花牌4枚です。手牌の7mは7pとしても7sとしても使えます。
            </p>
            <ul>
              <li>
                ・山から7mがめくれたときは、7p見立てと7s見立てのうち、のり枚数が大きい方を取ります。
              </li>
              <li>
                ・スーパービンゴとは異なり、花牌を2枚以上抜いているときに花牌がめくれると、6枚以上のるため突確に入ります。
              </li>
              <li>
                ・グランドクロス（東南西北を1枚ずつで暗槓）ができます。
              </li>
              <li>
                ・スーパービンゴと同様、7mを読み替えた後の手牌の中で、7p、7sを5枚以上使って和了ることはできません（麻雀の常識）。
              </li>
            </ul>
          </section>

          <section>
            <h3>和了種別と初期状態</h3>
            <p>
              リーチ役満、および天和・地和・人和は、777がなくても確変から始まります。同色の7が3枚以上あれば16Rになります。777の777や突確による昇格はそのままあります。
            </p>
            <table>
              <thead>
                <tr>
                  <th>種別</th>
                  <th>なし</th>
                  <th>777のみ</th>
                  <th>777の777</th>
                </tr>
              </thead>
              <tbody>
                <tr>
                  <td>通常手 / リーチなし役満</td>
                  <td>通常</td>
                  <td>確変</td>
                  <td>16R</td>
                </tr>
                <tr>
                  <td>リーチ役満・天地人和</td>
                  <td>確変</td>
                  <td>16R</td>
                  <td>16R</td>
                </tr>
              </tbody>
            </table>
          </section>

          <section>
            <h3>本シミュレーターで扱わないこと</h3>
            <ul>
              <li>
                ホームランビンゴ（カットビマークによる満塁・ホームランと、祝儀の2倍・4倍・6倍）は計算しません。
              </li>
              <li>
                河・他家の手牌・ドラ表示牌・王牌は、指定しない限り未知牌として山に残します。見えている牌は「山から除外」で除けます。各山に必ず入れたい牌は「山に確定」で指定します。
              </li>
              <li>一発・裏・赤・本役満などの祝儀枚数は、チューリップの枚数に含めません。</li>
            </ul>
          </section>
        </div>
      </div>
    </dialog>
  );
}
